"""Generate docs/features.md and docs/reference/{callbacks,patches}.md, and check them.

    python3 tools/docs/gen.py          # write the generated pages
    python3 tools/docs/gen.py --check  # fail if they are stale or docs/features.toml is wrong

Sources of truth, read here so the pages can't drift from them:
- docs/features.toml: the features, written by hand. Everything it names is checked: patches
  exist and every patch belongs to a feature, tests and files exist, every default test
  (tests/run.sh) belongs to a feature, py:/c:/plugin:/flake: names exist in the code.
- engine/patches/<ver>/series and each patch's Subject, Origin and SPDX-License-Identifier.
- engine/src/include/panda/callbacks/cb-defs.h: the callbacks and their comment blocks.
- tests/callbacks.py: which callbacks have no call site or abort at registration (the test fails
  when one of those starts working, so these sets stay true).
Run from anywhere; paths are relative to the repository root. Needs Python 3.11 (tomllib).
"""
import ast
import json
import re
import sys
import tomllib
import warnings
from pathlib import Path

# pandare2's source has escapes that Python warns about when parsing it; not ours to report here
warnings.filterwarnings("ignore", category=SyntaxWarning)

ROOT = Path(__file__).resolve().parents[2]
VERSION = next(iter(json.loads((ROOT / "engine/base.json").read_text())))
PATCHES = ROOT / "engine/patches" / VERSION
CB_DEFS = ROOT / "engine/src/include/panda/callbacks/cb-defs.h"
REPO = "https://github.com/panda-re/panda-ng"
OUTPUTS = ("docs/features.md", "docs/reference/patches.md", "docs/reference/callbacks.md")
GENERATED = "<!-- Generated by tools/docs/gen.py from {src}: edit that, then `nix run .#regen-docs`. -->\n\n"

errors = []


def err(msg):
    errors.append(msg)


# ---------------------------------------------------------------- sources

def patches():
    """[(number, filename, subject, origin, license)] in series order."""
    out = []
    for line in (PATCHES / "series").read_text().split("\n"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        f = ROOT / "engine/patches" / line
        text = f.read_text(errors="replace")
        head = text.split("\n---\n", 1)[0]
        m = re.search(r"^Subject: (?:\[PATCH[^\]]*\] )?(.*(?:\n [^\n]*)*)", head, re.M)
        subject = re.sub(r"\n ", " ", m.group(1)).strip() if m else f.name
        origin = (re.search(r"^Origin: (.*)$", head, re.M) or [None, "?"])[1].strip()
        # REUSE-IgnoreStart (a pattern, not this file's license)
        spdx = (re.search(r"^SPDX-License-Identifier: (.*)$", head, re.M) or [None, "?"])[1].strip()
        # REUSE-IgnoreEnd
        out.append((f.name[:4], f.name, subject, origin, spdx))
    return out


def callbacks():
    """{name: (signature, description)} from cb-defs.h's 'Callback ID' blocks, in enum order."""
    text = CB_DEFS.read_text()
    enum = re.search(r"typedef enum panda_cb_type \{(.*?)\}", text, re.S).group(1)
    names = [n.lower() for n in re.findall(r"^\s*PANDA_CB_(\w+)", enum, re.M) if n != "LAST"]
    out = {}
    for m in re.finditer(r"/\* Callback ID:\s*PANDA_CB_(\w+),?(.*?)\*/\s*([^;]*;)", text, re.S):
        name = m.group(1).lower()
        if name in out:
            continue
        body = m.group(2)
        # the first paragraph, without its "name:" label (some blocks name another callback)
        desc = ""
        for para in re.split(r"\n\s*\n", body):
            para = re.sub(r"^\s*\w+\s*:(?=\s)", "", para.strip(), count=1)
            para = " ".join(para.split())
            if para and not para.startswith("Arguments"):
                desc = para
                break
        sig = " ".join(m.group(3).split())
        out[name] = (sig, desc)
    for n in names:
        if n not in out:
            err(f"cb-defs.h: PANDA_CB_{n.upper()} has no 'Callback ID' comment block")
    return {n: out.get(n, ("", "")) for n in names}


def test_sets():
    """The literal sets/dicts at tests/callbacks.py's top level, without running it."""
    tree = ast.parse((ROOT / "tests/callbacks.py").read_text())
    want = {"ABORTS", "COVERED_ELSEWHERE", "NO_CALL_SITE", "EXERCISED_ONLY_ON"}
    out = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and getattr(node.targets[0], "id", None) in want:
            out[node.targets[0].id] = ast.literal_eval(node.value)
    return out


def default_tests():
    m = re.search(r'^DEFAULT_TESTS="([^"]*)"', (ROOT / "tests/run.sh").read_text(), re.M)
    return m.group(1).split()


_py_names = None


def py_names():
    """Every 'Class.method', 'Class', 'module.func' and 'func' defined in pandare2."""
    global _py_names
    if _py_names is None:
        _py_names = set()
        for f in (ROOT / "python/core/pandare2").rglob("*.py"):
            mod = f.stem
            for node in ast.parse(f.read_text(errors="replace")).body:
                if isinstance(node, ast.ClassDef):
                    _py_names.add(node.name)
                    for sub in node.body:
                        if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                            _py_names.add(f"{node.name}.{sub.name}")
                elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    _py_names.update({node.name, f"{mod}.{node.name}"})
            _py_names.add(mod)
    return _py_names


_c_text = None


def c_text():
    global _c_text
    if _c_text is None:
        dirs = [ROOT / "engine/src/include", ROOT / "include", ROOT / "plugins"]
        _c_text = "\n".join(p.read_text(errors="replace") for d in dirs for p in d.rglob("*.h"))
        # the engine's own API: lines the series adds to QEMU's headers and sources
        _c_text += "\n".join(l for p in PATCHES.glob("*.patch")
                             for l in p.read_text(errors="replace").split("\n") if l.startswith("+"))
    return _c_text


def check_api(feature, ref):
    kind, _, name = ref.partition(":")
    if kind == "py":
        if name not in py_names():
            err(f"{feature}: {ref}: not defined in python/core/pandare2")
    elif kind == "c":
        if not re.search(rf"\b{re.escape(name)}\b", c_text()):
            err(f"{feature}: {ref}: not in any header or patch")
    elif kind == "plugin":
        if name not in (ROOT / "plugins/config.panda").read_text().split():
            err(f"{feature}: {ref}: not in plugins/config.panda")
    elif kind == "flake":
        if not re.search(rf"\b{re.escape(name)}\b", (ROOT / "flake.nix").read_text()):
            err(f"{feature}: {ref}: not in flake.nix")
    elif kind == "qemu":
        pass  # an engine option or QMP command, shown as written
    else:
        err(f"{feature}: {ref}: unknown kind (py:, c:, plugin:, flake:, qemu:)")


def expand(spec):
    """'0025-0028' -> ['0025', '0026', '0027', '0028']."""
    a, _, b = spec.partition("-")
    return [f"{i:04d}" for i in range(int(a), int(b or a) + 1)]


def ranges(nums):
    """['0025','0026','0027','0030'] -> '0025-0027, 0030'."""
    ns = sorted(int(n) for n in nums)
    out, i = [], 0
    while i < len(ns):
        j = i
        while j + 1 < len(ns) and ns[j + 1] == ns[j] + 1:
            j += 1
        out.append(f"{ns[i]:04d}" if i == j else f"{ns[i]:04d}-{ns[j]:04d}")
        i = j + 1
    return ", ".join(out)


# ---------------------------------------------------------------- pages

STATUS = {"supported": "supported", "experimental": "experimental", "engine": "engine API"}


def features_page(manifest, pnums):
    feats = manifest["feature"]
    claimed = {}
    ids = set()
    for f in feats:
        fid = f["id"]
        if fid in ids:
            err(f"features.toml: duplicate id {fid}")
        ids.add(fid)
        for k in ("name", "summary", "status"):
            if k not in f:
                err(f"{fid}: missing {k}")
        if f.get("status") not in STATUS:
            err(f"{fid}: status must be one of {', '.join(STATUS)}")
        for spec in f.get("patches", []):
            for n in expand(spec):
                if n not in pnums:
                    err(f"{fid}: patch {n} is not in the series")
                claimed.setdefault(n, []).append(fid)
        for t in f.get("tests", []):
            if not (ROOT / t.split()[0]).exists():
                err(f"{fid}: test {t} does not exist")
        for d in f.get("docs", []):
            if not (ROOT / d.split("#")[0]).exists() and d.split("#")[0] not in OUTPUTS:
                err(f"{fid}: docs {d} does not exist")
        for a in f.get("api", []):
            check_api(fid, a)
    for n in pnums:
        if n not in claimed:
            err(f"patch {n} belongs to no feature in docs/features.toml")
    tested = {Path(t.split()[0]).stem for f in feats for t in f.get("tests", [])}
    for t in default_tests():
        if t not in tested:
            err(f"default test {t} (tests/run.sh) belongs to no feature in docs/features.toml")

    def link(path):
        # pages in docs/ link relatively; other repository files link to GitHub, so the links work
        # on the built site as well as when reading docs/ on GitHub
        target = path[len("docs/"):] if path.startswith("docs/") else f"{REPO}/blob/main/{path}"
        return f"[{path}]({target})"

    o = [GENERATED.format(src="docs/features.toml"), "# Features\n\n", manifest["intro"].strip(), "\n\n"]
    o.append("| feature | status | accelerators | tested on |\n|---|---|---|---|\n")
    for f in feats:
        o.append(f"| [{f['name']}](#{f['id']}) | {STATUS.get(f['status'], '?')} | "
                 f"{', '.join(f.get('accel', [])) or '-'} | {', '.join(f.get('tested_on', [])) or '**untested**'} |\n")
    o.append("\nStatus: **supported** is tested and meant for users; **experimental** works but its "
             "interface or coverage is still moving; **engine API** is used by tools built on the engine "
             "(penguin) rather than through pandare2.\n")
    for f in feats:
        o.append(f'\n<a id="{f["id"]}"></a>\n## {f["name"]}\n\n{f["summary"].strip()}\n\n')
        if f.get("limits"):
            o.append(f"**Limits.** {f['limits'].strip()}\n\n")
        if f.get("api"):
            o.append("**Use it:** " + ", ".join(f"`{a.partition(':')[2]}`" + (" (plugin)" if a.startswith("plugin:") else "")
                                                for a in f["api"]) + "\n\n")
        if f.get("docs"):
            o.append("**Docs:** " + ", ".join(link(d) for d in f["docs"]) + "\n\n")
        if f.get("tests"):
            o.append("**Tests:** " + ", ".join(f"`{t}`" for t in f["tests"]) + "\n\n")
        else:
            o.append("**Tests:** none yet.\n\n")
        if f.get("patches"):
            o.append(f"**Engine patches:** {ranges([n for s in f['patches'] for n in expand(s)])} "
                     f"([series](reference/patches.md))\n")
    return "".join(o), claimed


def patches_page(ps, claimed):
    o = [GENERATED.format(src=f"engine/patches/{VERSION}/series, its patches and docs/features.toml"),
         f"# The engine patch series\n\nQEMU {VERSION} plus {len(ps)} patches "
         f"(`engine/patches/{VERSION}/`). `engine/README.md` explains how to change the series; "
         f"`ORIGINS.md` there says where each patch comes from.\n\n",
         "| # | subject | feature | origin | license |\n|---|---|---|---|---|\n"]
    for n, _, subj, origin, spdx in ps:
        feats = ", ".join(f"[{fid}](../features.md#{fid})" for fid in claimed.get(n, []))
        subj = subj.replace("|", "\\|")
        o.append(f"| {n} | {subj} | {feats} | {origin} | {spdx} |\n")
    return "".join(o)


def callbacks_page(cbs, sets):
    aborts, none = sets.get("ABORTS", set()), sets.get("NO_CALL_SITE", {})
    only = sets.get("EXERCISED_ONLY_ON", {})
    for n in list(aborts) + list(none) + list(sets.get("COVERED_ELSEWHERE", set())):
        if n not in cbs:
            err(f"tests/callbacks.py names {n}, which is not a callback in cb-defs.h")
    served = [n for n in cbs if n not in aborts and n not in none]
    o = [GENERATED.format(src="cb-defs.h and tests/callbacks.py"),
         "# Callbacks\n\n",
         f"{len(cbs)} callback types (`engine/src/include/panda/callbacks/cb-defs.h`). "
         f"{len(served)} fire; {len(none)} are declared but have no call site in this engine yet, and "
         f"{len(aborts)} abort at registration. Register them from Python with the "
         "`@panda.cb_<name>` decorators, or from C with `panda_register_callback`.\n\n"
         "The status comes from `tests/callbacks.py`, which registers every callback on each test "
         "image and fails if one listed as missing starts firing, so this table stays true.\n\n",
         "| callback | status | when it runs |\n|---|---|---|\n"]
    for n, (sig, desc) in cbs.items():
        if n in aborts:
            st = "aborts at registration"
        elif n in none:
            st = "no call site" + ("" if none[n] == "no call site" else f" ({none[n]})")
        else:
            st = "fires" + (f" ({', '.join(sorted(only[n]))} only)" if n in only else "")
        first = re.split(r"(?<=\.)\s", desc, maxsplit=1)[0] if desc else ""
        first = first.replace("|", "\\|")
        o.append(f"| `{n}` | {st} | {first} |\n")
    o.append("\n## Signatures\n\n")
    for n, (sig, desc) in cbs.items():
        if sig:
            o.append(f"- `{n}`: `{sig}`\n")
    return "".join(o)


def main():
    check = "--check" in sys.argv
    manifest = tomllib.loads((ROOT / "docs/features.toml").read_text())
    ps = patches()
    feats, claimed = features_page(manifest, [p[0] for p in ps])
    pages = {
        "docs/features.md": feats,
        "docs/reference/patches.md": patches_page(ps, claimed),
        "docs/reference/callbacks.md": callbacks_page(callbacks(), test_sets()),
    }
    for rel, text in pages.items():
        p = ROOT / rel
        if check:
            if not p.exists() or p.read_text() != text:
                err(f"{rel} is stale: nix run .#regen-docs")
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
    for e in errors:
        print("error:", e, file=sys.stderr)
    if not check and not errors:
        print("wrote", ", ".join(pages))
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()
