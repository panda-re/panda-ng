#!/usr/bin/env python3
"""Write pandare2's system-call numbers for injection (python/core/pandare2/inject_numbers.py).

From syscalls2's Linux prototype tables (generated-in/linux_*_prototypes.txt): for each injector
ABI of panda/inject.h, every call's name (without sys_), number and argument count.

    python3 plugins/syscalls2/scripts/gen_inject_numbers.py [--check]
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TABLES = os.path.join(HERE, "..", "generated-in")
OUT = os.path.join(HERE, "..", "..", "..", "python", "core", "pandare2", "inject_numbers.py")

# PandaInjectAbi order (panda/inject.h); the table and the number range each takes
ABIS = [
    ("x86_64", "linux_x64", None),
    ("i386", "linux_x86", None),
    ("aarch64", "linux_arm64", None),
    ("arm", "linux_arm", None),
    ("riscv64", "linux_riscv64", None),
    ("mips_o32", "linux_mips", None),
    ("mips_n64", "linux_mips64", (5000, 6000)),
    ("ppc", "linux_ppc", None),
    ("ppc64", "linux_ppc64", None),
    # asm-generic numbering, as riscv64 (loongarch64 has no syscalls2 table)
    ("loongarch64", "linux_riscv64", None),
]

ALIASES = {"mmap_pgoff": "mmap2"}

LINE = re.compile(r"^(\d+)\s+\S+\s+sys_(\w+)\((.*)\);")


def table(name, rng):
    calls = {}
    with open(os.path.join(TABLES, f"{name}_prototypes.txt")) as f:
        for line in f:
            m = LINE.match(line)
            if not m:
                continue
            nr, call, params = int(m.group(1)), m.group(2), m.group(3).strip()
            if rng and not rng[0] <= nr < rng[1]:
                continue
            nargs = 0 if params in ("", "void") else params.count(",") + 1
            calls.setdefault(call, (nr, nargs))
    # the names programs know a call by, where the kernel's differs
    # (a 32-bit ABI's *_time32 call is the plain name where no time64 call has it: nanosleep)
    for kernel, alias in list(ALIASES.items()) + [(c, c[5:]) for c in list(calls)
                                                    if c.startswith("mips_")] + \
            [(c, c[:-7]) for c in list(calls) if c.endswith("_time32")]:
        if kernel in calls and alias not in calls:
            calls[alias] = calls[kernel]
    return calls


def render():
    out = ['"""System-call numbers and argument counts for panda.inject, per injector ABI.',
           "",
           "Generated by plugins/syscalls2/scripts/gen_inject_numbers.py from syscalls2's Linux",
           'prototype tables. Do not edit."""',
           "",
           "# ABI index (PandaInjectAbi) -> name",
           f"ABIS = {[a for a, _, _ in ABIS]!r}",
           "",
           "# name -> {call: (number, arguments)}",
           "NUMBERS = {"]
    for abi, name, rng in ABIS:
        calls = table(name, rng)
        out.append(f"    {abi!r}: {{")
        for call in sorted(calls):
            nr, nargs = calls[call]
            out.append(f"        {call!r}: ({nr}, {nargs}),")
        out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the file is out of date")
    a = ap.parse_args()
    text = render()
    if a.check:
        with open(OUT) as f:
            if f.read() != text:
                sys.exit(f"{OUT} is out of date: run {sys.argv[0]}")
        return
    with open(OUT, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
