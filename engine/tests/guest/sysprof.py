#!/usr/bin/env python3
"""sysprof.py <ver> <arch>: syscall profile for plugin/syscalls.c, from the
kernel's cosi (dwarf2json) file, as kernel-lift would supply it.  Writes
sysprof-<ver>-<arch>.txt.

Locations, evaluated at a handler's first instruction:
  r:NAME              a register (gdbstub name; mips: $N)
  m:NAME+OFF:SIZE     memory at register + OFF
  m:NAME&MASK+OFF:SIZE  memory at (register & MASK) + OFF
"""
import json
import lzma
import os
import sys
K, G = os.environ['KERNEL_DIR'], os.environ['GEN']

v, a = sys.argv[1], sys.argv[2]
h = os.path.dirname(os.path.abspath(__file__))
ka = {'aarch64': 'arm64'}.get(a, a)
d = json.load(lzma.open(f'{K}/{v}/cosi.{ka}.json.xz'))
S, T, F = d['symbols'], d['user_types'], d['functions']
mips = a.startswith('mips')
ptr = 4 if a in ('armel', 'mipsel', 'mipseb') else 8


def sym(n):
    s = S.get(n)
    return s['address'] if s and s.get('address') else None


def field(t, name, base=0):
    """Offset of @name in struct @t, looking into anonymous members."""
    for fname, fd in T[t]['fields'].items():
        if fname == name:
            return base + fd['offset']
        if fd.get('anonymous') or fname.startswith('unnamed_field'):
            sub = fd['type'].get('name')
            if sub in T:
                r = field(sub, name, base + fd['offset'])
                if r is not None:
                    return r
    return None


def ppc64_local_entry(path, big):
    """ELFv2: functions that set up the TOC (addis r2,r12 / addi r2,r2) are
    entered 8 bytes in by local callers, i.e. by the rest of the kernel."""
    import struct
    e = '>' if big else '<'
    b = open(path, 'rb').read()
    phoff, = struct.unpack_from(e + 'Q', b, 0x20)
    phentsize, phnum = struct.unpack_from(e + 'HH', b, 0x36)
    segs = []
    for i in range(phnum):
        o = phoff + i * phentsize
        typ, = struct.unpack_from(e + 'I', b, o)
        off, vaddr, _, filesz = struct.unpack_from(e + 'QQQQ', b, o + 8)
        if typ == 1:
            segs.append((vaddr, off, filesz))
    def fix(x):
        if not x:
            return x
        va = int(x, 16)
        for vaddr, off, sz in segs:
            if vaddr <= va < vaddr + sz:
                i0, i1 = struct.unpack_from(e + 'II', b, off + va - vaddr)
                if i0 >> 16 == 0x3c4c and i1 >> 16 == 0x3842:
                    return hex(va + 8)
        return x
    return fix


def reg(n):
    return f'${n}' if mips else n


out = [f'# generated by sysprof.py from cosi.{ka}.json.xz', f'arch {a}', f'ptr {ptr}']

# where the syscall arguments are when a handler is entered
WRAP = {'x86_64': '__x64_sys_', 'aarch64': '__arm64_sys_', 'riscv64': '__riscv_sys_'}
prefix = WRAP.get(a, 'sys_')
probe = F.get(prefix + 'openat') or F.get('__se_sys_openat')
wrapper = len(probe['parameters']) == 1 and \
    probe['parameters'][0]['type'].get('subtype', {}).get('name') == 'pt_regs'
assert wrapper == (a in WRAP), (a, probe)
if a == 'x86_64':
    base, names = 'rdi', ['di', 'si', 'dx', 'r10', 'r8', 'r9']
    args = [f'm:{base}+{field("pt_regs", n)}:8' for n in names]
elif a == 'aarch64':
    args = [f'm:x0+{8 * i}:8' for i in range(6)]          # pt_regs.regs[i]
elif a == 'riscv64':
    # do_trap_ecall_u saves a0 in orig_a0 and sets a0 = -ENOSYS before dispatch
    args = [f'm:a0+{field("pt_regs", n)}:8' for n in ('orig_a0', 'a1', 'a2', 'a3', 'a4', 'a5')]
elif a == 'armel':
    # entry-common.S pushes r4, r5 (the fifth and sixth arguments)
    args = ['r:r0', 'r:r1', 'r:r2', 'r:r3', 'm:sp+0:4', 'm:sp+4:4']
elif a in ('mipsel', 'mipseb'):
    # o32: scall32-o32.S stores arguments 5 and 6 at 16(sp) and 20(sp)
    args = ['r:$4', 'r:$5', 'r:$6', 'r:$7', 'm:$29+16:4', 'm:$29+20:4']
elif a.startswith('mips64'):
    args = [f'r:${n}' for n in range(4, 10)]
elif a.startswith('powerpc64'):
    args = [f'r:r{n}' for n in range(3, 9)]
elif a == 'loongarch64':
    args = [f'r:r{n}' for n in range(4, 10)]
out.append(f'wrapper {int(wrapper)}')
out.append('args ' + ' '.join(args))

# return value, return address and stack pointer
RET = {'x86_64': ('rax', 'm:rsp+0:8', 'rsp', 8), 'aarch64': ('x0', 'r:x30', 'sp', 0),
       'riscv64': ('a0', 'r:ra', 'sp', 0), 'armel': ('r0', 'r:lr', 'sp', 0),
       'loongarch64': ('r4', 'r:r1', 'r3', 0)}
if mips:
    ret, ra, sp, delta = '$2', 'r:$31', '$29', 0
elif a.startswith('powerpc64'):
    ret, ra, sp, delta = 'r3', 'r:lr', 'r1', 0
else:
    ret, ra, sp, delta = RET[a]
out += [f'ret {ret}', f'ra {ra}', f'sp {sp}', f'spdelta {delta}']

# the current task, in kernel mode
ti_task = field('thread_info', 'task') if 'thread_info' in T else None
if a == 'x86_64':
    cur = f'm:gs_base+{sym("pcpu_hot") + field("pcpu_hot", "current_task")}:8'
elif a == 'aarch64':
    cur = 'r:SP_EL0'
elif a == 'riscv64':
    cur = 'r:tp'
elif a.startswith('powerpc64'):
    cur = f'm:r13+{field("paca_struct", "__current")}:8'
elif a == 'armel':
    cur = f'm:sp&{~8191 & 0xffffffff:#x}+{ti_task}:4' if ti_task is not None else 'r:TPIDRURO'
elif mips:
    cur = f'm:$28+{ti_task}:{ptr}'
elif a == 'loongarch64':
    cur = f'm:r2+{ti_task}:8'
out.append(f'current {cur}')
# the current task at the user/kernel boundary (trap mode): the kernel's
# per-CPU base is in a register the user task cannot change
if a == 'x86_64':
    out.append(f'ucurrent m:k_gs_base+{sym("pcpu_hot") + field("pcpu_hot", "current_task")}:8')
elif a == 'aarch64':
    out.append(f'ucurrent m:TPIDR_EL1+{sym("__entry_task"):#x}:8')
out.append('task ' + ' '.join(f'{k}={field("task_struct", k)}'
                              for k in ('comm', 'pid', 'tgid', 'mm', 'start_time', 'nsproxy')))
# analysis scope (igloo_in_scope): task->nsproxy->uts_ns != &init_uts_ns
out.append(f'nsproxy uts_ns={field("nsproxy", "uts_ns")} init_uts_ns={sym("init_uts_ns"):#x}')
out.append('meta ' + ' '.join(f'{k}={field("syscall_metadata", k)}'
                              for k in ('name', 'syscall_nr', 'nb_args', 'types', 'args')))

boot = sym('start_kernel')
if a.startswith('powerpc64'):
    # head_64.S calls start_kernel directly: ELFv2 local entry, past the TOC setup
    boot = int(ppc64_local_entry(f'{K}/{v}/vmlinux.{a}',
                                 a == 'powerpc64')(hex(boot)), 16)
out.append(f'bootstrap {boot:#x}')
out.append(f'fork_child {sym("ret_from_fork"):#x}')
# the trap engine's reaper: release_task(p) drops a dead task's calls
out.append(f'reaper {sym("release_task"):#x}')

# handlers: one per syscall that has metadata
n_sys = 0
for m in sorted(x for x in S if x.startswith('__syscall_meta__')):
    name = m[len('__syscall_meta__'):]
    hnd = sym(prefix + name) or sym('sys_' + name)
    if not hnd:
        continue
    out.append(f'sys {name} {hnd:#x} {sym(m):#x}')
    n_sys += 1

# compat ABIs (trap mode): numbers from the uapi headers, names as the
# native metadata has them
import re
COMPAT = {'x86_64': ('i386', '/usr/include/x86_64-linux-gnu/asm/unistd_32.h'),
          'aarch64': ('arm', '/usr/arm-linux-gnueabi/include/asm/unistd-eabi.h')}
n_c = 0
if a in COMPAT:
    cabi, hdr = COMPAT[a]
    native = {l.split()[1] for l in out if l.startswith('sys ')}
    for name, num in re.findall(r'#define __NR_(\w+)\s+\(?(?:__NR_SYSCALL_BASE\s*\+\s*)?(\d+)\)?',
                                open(hdr).read()):
        for cand in (name, re.sub(r'(32|64)$', '', name), name.lstrip('_')):
            if cand in native:
                out.append(f'csys {cabi} {cand} {num}')
                n_c += 1
                break
print(f'{n_c} compat syscalls')
open(f'{G}/sysprof-{v}-{a}.txt', 'w').write('\n'.join(out) + '\n')
print(v, a, f'wrapper={int(wrapper)}', f'{n_sys} syscalls', f'current={cur}')
