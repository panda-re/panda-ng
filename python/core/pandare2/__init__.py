"""
pandare2 is the Python interface to panda-ng (PANDA on QEMU 11.1). A `Panda` object is a virtual
machine: a script registers callbacks on its execution, loads C plugins, drives the guest through
its serial console, and records and replays executions.

Most of the API is on `pandare2.panda.Panda`. `pandare2.machine.MachineBuilder` describes a
machine to build (the engine's configurable machine, or an external board), and
`pandare2.pyplugin.PyPlugin` is the base class for Python plugins. `python -m pandare2.mkimage`
builds guest images (see the repository's tests/README.md).

The scripts in the repository's tests/ directory are working examples: each docstring says what
the script checks and how to run it.
"""

