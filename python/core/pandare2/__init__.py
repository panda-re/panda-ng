class Callbacks:
    '''
    PANDA's core callbacks. This class only exists for documentation: the callbacks are
    decorators on a `Panda` object, `@panda.cb_<name>`, one for each PANDA_CB_<NAME> in the
    repository's engine/src/include/panda/callbacks/cb-defs.h, which gives each one's arguments
    and return value. The decorated function receives those arguments and returns what the
    callback must return.

        panda = Panda(arch="x86_64")

        @panda.cb_before_block_exec
        def before_block(cpu, tb):
            print(hex(panda.current_pc(cpu)))

    `@panda.cb_<name>(name=..., procname=..., enabled=...)` takes options; see
    `Panda.register_cb_decorators`.
    '''

    def __init__(self):
        raise RuntimeError("The callbacks class is only used for documentation. Callback " \
                           "decorators should be accessed through @panda.cb_[calback_name] " \
                           "where panda is the name of your pandare2.Panda() object")
