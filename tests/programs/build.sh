# Assembles the API test's guest programs into api_programs.py (run in the colima VM, or anywhere
# with nix). The ELFs are static, text at 0x400000 and the marker in .data, stripped.
set -e
cd "$(dirname "$0")"
out=api_programs.py
echo '"""Generated by tests/programs/build.sh from api_<arch>.S; base64 static ELFs."""' > $out
echo 'PROGRAMS = {' >> $out
for a in x86_64 aarch64 riscv64; do
  case $a in x86_64) cross=gnu64;; aarch64) cross=aarch64-multiplatform;; riscv64) cross=riscv64;; esac
  bin=$(nix build --no-link --print-out-paths "nixpkgs#pkgsCross.$cross.buildPackages.binutils-unwrapped^out")
  # Unprefixed when the target is the build machine's own arch.
  pfx=$(ls $bin/bin | sed -n 's/-as$/-/p' | head -1)
  tmp=$(mktemp -d)
  $bin/bin/${pfx}as api_$a.S -o $tmp/p.o
  $bin/bin/${pfx}ld -static -s -z noseparate-code -Ttext-segment=0x400000 -e _start $tmp/p.o -o $tmp/p
  echo "    \"$a\": \"$(base64 -w0 $tmp/p)\"," >> $out
  rm -r $tmp
done
echo '}' >> $out
