# Assembles the test guest programs into <name>_programs.py (run in the colima VM, or anywhere
# with nix): api_<arch>.S for tests/api.py, blocks_<arch>.S for tests/blocks.py, mem_<arch>.S for
# tests/mem.py, calls_<arch>.S for tests/calls.py and tests/rrcb.py, procs_<arch>.S for
# tests/asidstory.py, adbits_<arch>.S for tests/fastrestore.py, mmio_<arch>.S for tests/mmio.py,
# fastcov_<arch>.S for tests/fastcov.py, syscalls_<arch>.S for tests/syscalls.py, answers_<arch>.S
# for tests/hypercall_rr.py, flushsmp_<arch>.S for tests/flush_smp.py, agent.c for tests/testmachine.py,
# sctruth_<arch>.S, scpaths.c and scwork.c for tests/syscall_truth.py.
# A <name>.c program is freestanding (no libc; tests/programs/sys.h is its system layer), built
# with gcc -nostdlib for each arch in its list below; a <name>_<arch>.S is assembled for each arch
# it exists for. i386 is a 32-bit task on the x86_64 guest.
# The ELFs are static, text at 0x400000 (the agent's at 0x10000000), stripped. Arguments: the names to build (default: all).
set -e
cd "$(dirname "$0")"
names=${*:-api blocks mem calls procs adbits mmio fastcov syscalls answers flushsmp agent scpaths sctruth scwork}
# nix builds here are substitutions from the binary cache; never more than one job
NIX="nix build --no-link --print-out-paths --max-jobs 1 --cores 8"
for name in $names; do
  out=${name}_programs.py
  # The agent away from the programs (testlib.PROGRAM_BASE), so that its calls are never theirs.
  text=0x400000; [ $name = agent ] && text=0x10000000
  case $name in
    agent | scpaths | scwork) archs="x86_64 aarch64 arm i386 riscv64 mipsel mips mips64el mips64 ppc ppc64 ppc64le"
      src=${name}.c ;;
    sctruth) archs="x86_64 i386" src="${name}_<arch>.S" ;;
    *) archs="x86_64 aarch64 riscv64" src="${name}_<arch>.S" ;;
  esac
  echo "\"\"\"Generated by tests/programs/build.sh from ${src}; base64 static ELFs.\"\"\"" > $out
  echo 'PROGRAMS = {' >> $out
  for a in $archs; do
    # kernels with 16 or 64 KiB pages load segments aligned for them
    asflags= ldflags= ccflags= big=-Wl,-z,max-page-size=65536
    case $a in x86_64) cross=gnu64;; i386) cross=gnu64 asflags=--32 ldflags="-m elf_i386"
        [ -e ${name}.c ] && cross=gnu32 ldflags=;;
      aarch64) cross=aarch64-multiplatform ccflags=-mno-outline-atomics;;
      arm) cross=armv7l-hf-multiplatform ccflags=-marm;; riscv64) cross=riscv64 ldflags=-Wl,--no-relax;;
      mipsel | mips | mips64el | mips64) ccflags="-mno-abicalls -fno-pic" ldflags=$big;;&
      mipsel) cross=mipsel-linux-gnu;; mips) cross=mips-linux-gnu;;
      mips64el) cross=mips64el-linux-gnuabi64;; mips64) cross=mips64-linux-gnuabi64;;
      ppc) cross=ppc32 ldflags=$big;; ppc64) cross=ppc64-elfv2 ccflags=-mabi=elfv2 ldflags=$big;;
      ppc64le) cross=powernv ldflags=$big;; esac
    tmp=$(mktemp -d)
    if [ -e ${name}.c ]; then
      # CC_<arch>: another cross gcc for the arch (any libc: the programs use none)
      ccvar=CC_$a
      if [ -n "${!ccvar:-}" ]; then
        gcc=${!ccvar}
      else
        cc=$($NIX "nixpkgs#pkgsCross.$cross.stdenv.cc^out")
        gcc=$cc/bin/$(ls $cc/bin | grep -m1 'gcc$')
      fi
      $gcc -Os -static -nostdlib -ffreestanding -fno-stack-protector -fno-pie -no-pie \
        -fcf-protection=none -fno-asynchronous-unwind-tables -fno-builtin -s $ccflags \
        -Wl,-z,noseparate-code -Wl,-Ttext-segment=$text -Wl,--build-id=none -Wl,-z,max-page-size=4096 -Wl,-e,_start $ldflags ${name}.c -lgcc -o $tmp/p
    else
      bin=$($NIX "nixpkgs#pkgsCross.$cross.buildPackages.binutils-unwrapped^out")
      # Unprefixed when the target is the build machine's own arch.
      pfx=$(ls $bin/bin | sed -n 's/-as$/-/p' | head -1)
      $bin/bin/${pfx}as $asflags ${name}_$a.S -o $tmp/p.o
      $bin/bin/${pfx}ld $ldflags -static -s -z noseparate-code -Ttext-segment=0x400000 -e _start $tmp/p.o -o $tmp/p
    fi
    echo "    \"$a\": \"$(base64 -w0 $tmp/p)\"," >> $out
    rm -r $tmp
  done
  echo '}' >> $out
done
