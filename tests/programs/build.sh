# Assembles the test guest programs into <name>_programs.py (run in the colima VM, or anywhere
# with nix): api_<arch>.S for tests/api.py, blocks_<arch>.S for tests/blocks.py, mem_<arch>.S for
# tests/mem.py, calls_<arch>.S for tests/calls.py and tests/rrcb.py, procs_<arch>.S for
# tests/asidstory.py, adbits_<arch>.S for tests/fastrestore.py, mmio_<arch>.S for tests/mmio.py,
# fastcov_<arch>.S for tests/fastcov.py, syscalls_<arch>.S for tests/syscalls.py, answers_<arch>.S
# for tests/hypercall_rr.py, agent.c for tests/testmachine.py, sccover_<arch>.S and scpaths.c for
# tests/syscall_cover.py, sctruth_<arch>.S and scwork.c for tests/syscall_truth.py.
# A <name>.c program is freestanding (no libc; tests/programs/sys.h is its system layer), built
# with gcc -nostdlib for each arch in its list below; a <name>_<arch>.S is assembled for each arch
# it exists for. i386 is a 32-bit task on the x86_64 guest.
# The ELFs are static, text at 0x400000, stripped. Arguments: the names to build (default: all).
set -e
cd "$(dirname "$0")"
names=${*:-api blocks mem calls procs adbits mmio fastcov syscalls answers agent sccover scpaths sctruth scwork}
# nix builds here are substitutions from the binary cache; never more than one job
NIX="nix build --no-link --print-out-paths --max-jobs 1 --cores 8"
for name in $names; do
  out=${name}_programs.py
  case $name in
    agent | scpaths | scwork) archs="x86_64 aarch64" src=${name}.c ;;
    sccover) archs="x86_64 i386 aarch64" src="${name}_<arch>.S" ;;
    sctruth) archs="x86_64 i386" src="${name}_<arch>.S" ;;
    *) archs="x86_64 aarch64 riscv64" src="${name}_<arch>.S" ;;
  esac
  echo "\"\"\"Generated by tests/programs/build.sh from ${src}; base64 static ELFs.\"\"\"" > $out
  echo 'PROGRAMS = {' >> $out
  for a in $archs; do
    asflags= ldflags=
    case $a in x86_64) cross=gnu64;; i386) cross=gnu64 asflags=--32 ldflags="-m elf_i386";;
      aarch64) cross=aarch64-multiplatform;; riscv64) cross=riscv64;; esac
    tmp=$(mktemp -d)
    if [ -e ${name}.c ]; then
      cc=$($NIX "nixpkgs#pkgsCross.$cross.stdenv.cc^out")
      ccname=$(ls $cc/bin | grep -m1 'gcc$')
      $cc/bin/$ccname -Os -static -nostdlib -ffreestanding -fno-stack-protector -fno-pie -no-pie \
        -fcf-protection=none -fno-asynchronous-unwind-tables -fno-builtin -s \
        -Wl,-z,noseparate-code -Wl,-Ttext-segment=0x400000 -Wl,--build-id=none ${name}.c -o $tmp/p
    else
      bin=$($NIX "nixpkgs#pkgsCross.$cross.buildPackages.binutils-unwrapped^out")
      # Unprefixed when the target is the build machine's own arch.
      pfx=$(ls $bin/bin | sed -n 's/-as$/-/p' | head -1)
      $bin/bin/${pfx}as $asflags ${name}_$a.S -o $tmp/p.o
      $bin/bin/${pfx}ld $ldflags -static -s -z noseparate-code -Ttext-segment=0x400000 -e _start $tmp/p.o -o $tmp/p
    fi
    echo "    \"$a\": \"$(base64 -w0 $tmp/p)\"," >> $out
    rm -r $tmp
  done
  echo '}' >> $out
done
