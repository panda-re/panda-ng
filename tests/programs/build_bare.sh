# Assembles tests/blocks_bare.py's bare-metal guests (bare_<arch>.S) into bare_programs.py (run in
# the colima VM, or anywhere with nix): base64 ELFs plus their labels' addresses.
# mips: linked at 0x80100000 (kseg0) for malta's -kernel; ppc: at the reset vector 0xfff00100 for
# g3beige's -bios.
set -e
cd "$(dirname "$0")"
out=bare_programs.py
echo '"""Generated by tests/programs/build_bare.sh from bare_<arch>.S: base64 ELFs and label addresses."""' > $out
echo 'PROGRAMS = {' >> $out
for a in mips ppc; do
  case $a in mips) cross=mips-linux-gnu; text=0x80100000;; ppc) cross=ppc-embedded; text=0xfff00100;; esac
  bin=$(nix build --no-link --print-out-paths "nixpkgs#pkgsCross.$cross.buildPackages.binutils-unwrapped^out")
  pfx=$(ls $bin/bin | sed -n 's/-as$/-/p' | head -1)
  tmp=$(mktemp -d)
  $bin/bin/${pfx}as bare_$a.S -o $tmp/p.o
  $bin/bin/${pfx}ld -N -Ttext=$text -e _start $tmp/p.o -o $tmp/p
  labels=$($bin/bin/${pfx}nm $tmp/p | awk '$2 == "t" || $2 == "T" { printf "\"%s\": 0x%s, ", $3, $1 }')
  echo "    \"$a\": {\"elf\": \"$(base64 -w0 $tmp/p)\"," >> $out
  echo "        \"labels\": {$labels}}," >> $out
  rm -r $tmp
done
echo '}' >> $out
