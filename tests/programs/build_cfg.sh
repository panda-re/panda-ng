# Assembles tests/machine.py's bare-metal programs (cfg_<arch>.S) into cfg_programs.py (run in the
# colima VM, or anywhere with nix). Static ELFs, text at each arch's RAM base, not stripped.
set -e
cd "$(dirname "$0")"
out=cfg_programs.py
echo '"""Generated by tests/programs/build_cfg.sh from cfg_<arch>.S; base64 static ELFs."""' > $out
echo 'PROGRAMS = {' >> $out
for a in aarch64 arm riscv64 at91; do
  case $a in aarch64) cross=aarch64-multiplatform; base=0x40000000;; arm) cross=arm-embedded; base=0x40000000;;
    riscv64) cross=riscv64; base=0x80000000;; at91) cross=arm-embedded; base=0x20008000;; esac
  bin=$(nix build --no-link --print-out-paths "nixpkgs#pkgsCross.$cross.buildPackages.binutils-unwrapped^out")
  pfx=$(ls $bin/bin | sed -n 's/-as$/-/p' | head -1)
  tmp=$(mktemp -d)
  $bin/bin/${pfx}as $([ $a = at91 ] && echo -mcpu=arm926ej-s) cfg_$a.S -o $tmp/p.o
  $bin/bin/${pfx}ld -static -z noseparate-code -z max-page-size=4096 -Ttext=$base -e _start $tmp/p.o -o $tmp/p
  echo "    \"$a\": \"$(base64 -w0 $tmp/p)\"," >> $out
  rm -r $tmp
done
echo '}' >> $out
